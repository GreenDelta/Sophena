package sophena.calc.biogas.runtime;

import java.util.UUID;

import org.jspecify.annotations.NullMarked;
import org.jspecify.annotations.Nullable;
import org.openlca.commons.Res;

import sophena.calc.biogas.BiogasPlantCHP;
import sophena.calc.biogas.BiogasPlants;
import sophena.calc.biogas.runtime.eblocks.EblockSearch;
import sophena.calc.biogas.runtime.ehours.EHourSearch;
import sophena.model.ProducerProfile;
import sophena.model.Stats;
import sophena.model.biogas.BiogasPlant;

/// The runtime result of a biogas plant calculation: the gas that is produced
/// by the substrates of the plant and the hours of the year in which the plant
/// runs.
///
/// The run hours can be calculated with two algorithms, see `BiogasAlgorithm`.
/// The runtime result also contains the producer profile of the plant, which is
/// created with the default temperature (see `PRODUCER_TEMPERATURE`), and the
/// storage profile, which contains the gas that is in the biogas storage (in
/// m³) at the end of each hour.
///
/// The `gasStorageSize` of a result is the effective size that was used for
/// the calculation, see `BiogasPlants#effectiveGasStorageSizeOf(BiogasPlant)`.
///
/// The ramp hours (1/8 of the power before and after a block) are not included
/// in the run flags; see `rampsAt(int)` and `isOperating(int)`. They are added
/// when the producer profile and the generated electricity are calculated. The
/// heat losses of the plant (`heatLoss`) are subtracted from the producer
/// profile, so it contains the usable heat that is fed into the heat network.
///
/// The `generatedElectricity` is the electricity in kWh that is generated by
/// the CHP in one year, in the full-load hours and in the ramp hours. It is the
/// gross value: the cable and transformer losses and the internal power demand
/// are not subtracted. The rated power (Bemessungsleistung) is derived from it,
/// see `ratedPower()`.
@NullMarked
public record BiogasRuntimeResult(
	BiogasProfile biogasProfile,
	double gasStorageSize,
	boolean[] runFlags,
	ProducerProfile producerProfile,
	double generatedElectricity
) {

	/// The temperature in °C that is used for the `producerProfile` of a
	/// result. The method `asProducerProfile` can be used to create a profile
	/// with another temperature.
	public static final double PRODUCER_TEMPERATURE = 95.0;

	/// Calculates the plant with the default algorithm
	/// (`BiogasAlgorithm.DEFAULT`) and returns an error when the plant cannot
	/// be calculated with it.
	public static Res<BiogasRuntimeResult> calculate(@Nullable BiogasPlant plant) {
		return calculate(plant, BiogasAlgorithm.DEFAULT);
	}

	/// Calculates the plant with the given algorithm and returns an error with
	/// a message that describes the problem when the plant cannot be calculated
	/// with it, e.g. when the gas storage is too small for the minimum runtime
	/// of the plant.
	public static Res<BiogasRuntimeResult> calculate(
		@Nullable BiogasPlant plant, @Nullable BiogasAlgorithm algorithm
	) {
		if (plant == null)
			return Res.error("No biogas plant provided");
		if (algorithm == null)
			return Res.error("no algorithm for the biogas plant given");
		var flags = switch (algorithm) {
			case HOURS -> EHourSearch.runFlags(plant);
			case BLOCKS -> EblockSearch.runFlags(plant);
		};
		return flags.then(runFlags -> {
			var profile = BiogasProfile.of(plant);
			return Res.ok(new BiogasRuntimeResult(
				profile,
				BiogasPlants.effectiveGasStorageSizeOf(plant),
				runFlags,
				producerProfileOf(plant, runFlags, PRODUCER_TEMPERATURE),
				generatedElectricityOf(plant, runFlags)));
		});
	}

	/// The rated power (Bemessungsleistung) of the plant in kW: the generated
	/// electricity of the year divided by the hours of the year. This is the
	/// mean electric power of the plant over the whole year.
	public double ratedPower() {
		return generatedElectricity / Stats.HOURS;
	}

	/// An empty result. It is used by callers that need a producer profile for
	/// a plant that cannot be calculated, e.g. when the plant is edited: an
	/// edit should always be possible, also when the plant is not complete.
	public static BiogasRuntimeResult emptyOf(BiogasPlant plant) {
		var runFlags = new boolean[Stats.HOURS];
		return new BiogasRuntimeResult(
			BiogasProfile.empty(),
			0,
			runFlags,
			producerProfileOf(plant, runFlags, PRODUCER_TEMPERATURE),
			0);
	}

	/// Creates the producer profile of the given plant with the given
	/// temperature in °C from the run flags of this result. The stored
	/// `producerProfile` was created with `PRODUCER_TEMPERATURE`.
	public ProducerProfile asProducerProfile(
		BiogasPlant plant, double temperature
	) {
		return producerProfileOf(plant, runFlags, temperature);
	}

	/// The number of ramps (0, 1 or 2) in the given hour. A ramp is an hour
	/// directly before or after a block of full-load hours, in which the CHP
	/// runs with 1/8 of its power. An hour between two blocks has two ramps.
	/// Full-load hours and hours outside the year have no ramps.
	public int rampsAt(int hour) {
		return rampsAt(runFlags, hour);
	}

	/// Returns `true` when the CHP runs in the given hour, under full load or
	/// in a ramp.
	public boolean isOperating(int hour) {
		return isFullLoad(runFlags, hour) || rampsAt(hour) > 0;
	}

	private static int rampsAt(boolean[] runFlags, int hour) {
		if (hour < 0 || hour >= runFlags.length || runFlags[hour])
			return 0;
		int ramps = 0;
		if (isFullLoad(runFlags, hour - 1)) {
			ramps++;
		}
		if (isFullLoad(runFlags, hour + 1)) {
			ramps++;
		}
		return ramps;
	}

	private static boolean isFullLoad(boolean[] runFlags, int hour) {
		return hour >= 0 && hour < runFlags.length && runFlags[hour];
	}

	/// The electricity in kWh that is generated by the CHP: the full electric
	/// power in the full-load hours and 1/8 of it per ramp.
	private static double generatedElectricityOf(
		BiogasPlant plant, boolean[] runFlags
	) {
		double power = BiogasPlantCHP.of(plant).electricPower();
		if (power <= 0)
			return 0;
		double sum = 0;
		for (int h = 0; h < runFlags.length; h++) {
			sum += runFlags[h]
				? power
				: rampsAt(runFlags, h) * power / 8;
		}
		return sum;
	}

	private static ProducerProfile producerProfileOf(
		BiogasPlant plant, boolean[] runFlags, double temperature
	) {
		var profile = new ProducerProfile();
		profile.id = UUID.randomUUID().toString();
		profile.minPower = new double[Stats.HOURS];
		profile.maxPower = new double[Stats.HOURS];
		profile.temperaturLevel = new double[Stats.HOURS];
		double power = BiogasPlantCHP.of(plant).thermalPower();
		if (power <= 0)
			return profile;

		double heatLoss = plant.settings != null
			? plant.settings.heatLoss
			: 0;

		int n = runFlags.length;
		for (int h = 0; h < n; h++) {
			double hourPower = runFlags[h]
				? power
				: rampsAt(runFlags, h) * power / 8;
			if (hourPower > 0) {
				profile.maxPower[h] = hourPower;
				profile.temperaturLevel[h] = temperature;
			}
		}

		// the heat losses that occur before the heat is fed into the heat
		// network reduce the usable heat in the producer profile
		if (heatLoss > 0) {
			for (int h = 0; h < n; h++) {
				if (profile.maxPower[h] <= 0)
					continue;
				profile.maxPower[h] = Math.max(
					0, profile.maxPower[h] - heatLoss);
			}
		}

		return profile;
	}
}
